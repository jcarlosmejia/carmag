#!/usr/bin/env node
/**
 * CARMAG TRANSPORTS — responsive image pipeline.
 *
 * Reads `scripts/photos.config.mjs`, crops each source in `photos/`, and writes
 * AVIF, WebP and JPEG renditions to `public/images/` plus the typed manifest
 * `src/data/imageManifest.ts`. Components read the manifest by slot; an empty
 * slot renders the non-photo layout, so photos can be added or replaced
 * without touching components.
 *
 * NEVER UPSCALE: rendition widths are clamped to the cropped source width.
 *
 * Usage: npm run images
 */

import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import photos from './photos.config.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'photos');
const OUT_DIR = path.join(ROOT, 'public', 'images');
const MANIFEST = path.join(ROOT, 'src', 'data', 'imageManifest.ts');
const WIDTHS = [480, 768, 1080, 1600];
const SLOTS = ['hero', 'hero-mobile', 'caja-seca', 'plataforma', 'operacion'];

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const assets = [];
for (const photo of photos) {
  if (![...SLOTS, 'gallery'].includes(photo.slot)) throw new Error(`${photo.slug}: unknown slot ${photo.slot}`);
  if (!photo.alt) throw new Error(`${photo.slug}: alt text is required`);

  const src = sharp(path.join(SOURCE_DIR, photo.file)).rotate();
  const meta = await src.metadata();
  const portrait = (meta.orientation ?? 1) >= 5;
  const [sw, sh] = portrait ? [meta.height, meta.width] : [meta.width, meta.height];

  // Fractional region first, then the largest box of the target ratio inside it.
  const r = photo.region ?? { left: 0, top: 0, width: 1, height: 1 };
  const rw = Math.round(sw * r.width);
  const rh = Math.round(sh * r.height);
  const cw = Math.min(rw, Math.round(rh * photo.ratio));
  const ch = Math.round(cw / photo.ratio);
  const crop = {
    left: Math.round(sw * r.left + (rw - cw) / 2),
    top: Math.round(sh * r.top + (rh - ch) / 2),
    width: cw,
    height: ch,
  };

  const widths = [...new Set([...WIDTHS.filter((w) => w < cw), Math.min(cw, WIDTHS.at(-1))])];
  const renditions = [];
  for (const width of widths) {
    const base = sharp(path.join(SOURCE_DIR, photo.file)).rotate().extract(crop).resize({ width });
    const name = `${photo.slug}-${width}`;
    await base.clone().avif({ quality: 52 }).toFile(path.join(OUT_DIR, `${name}.avif`));
    await base.clone().webp({ quality: 74 }).toFile(path.join(OUT_DIR, `${name}.webp`));
    await base.clone().jpeg({ quality: 78, mozjpeg: true }).toFile(path.join(OUT_DIR, `${name}.jpg`));
    renditions.push({
      width,
      avif: `/images/${name}.avif`,
      webp: `/images/${name}.webp`,
      jpg: `/images/${name}.jpg`,
    });
  }

  assets.push({
    slot: photo.slot,
    asset: {
      slug: photo.slug,
      width: widths.at(-1),
      height: Math.round(widths.at(-1) / photo.ratio),
      alt: photo.alt,
      ...(photo.caption ? { caption: photo.caption } : {}),
      renditions,
    },
  });
}

const slotImages = Object.fromEntries(assets.filter((a) => a.slot !== 'gallery').map((a) => [a.slot, a.asset]));
const galleryImages = assets.filter((a) => a.slot === 'gallery').map((a) => a.asset);

await writeFile(
  MANIFEST,
  `/**
 * GENERATED by scripts/build-images.mjs from scripts/photos.config.mjs.
 * Do not edit by hand: run \`npm run images\`.
 */

export type ImageSlot = ${SLOTS.map((s) => `'${s}'`).join(' | ')};

export type ImageRendition = { width: number; avif: string; webp: string; jpg: string };

export type ImageAsset = {
  slug: string;
  width: number;
  height: number;
  alt: string;
  caption?: string;
  renditions: readonly ImageRendition[];
};

export const slotImages: Partial<Record<ImageSlot, ImageAsset>> = ${JSON.stringify(slotImages, null, 2)};

export const galleryImages: readonly ImageAsset[] = ${JSON.stringify(galleryImages, null, 2)};
`,
);
console.log(`imageManifest.ts written — ${assets.length} image(s).`);
